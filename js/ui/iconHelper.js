/**
 * 解析并输出高品质魔幻贴图图标
 * @param {string|object} itemOrKey 物品对象、宠物对象、槽位标识或道具ID
 * @param {object} options 渲染配置 { size: 'w-7 h-7', className: '', fallback: '' }
 * @returns {string} HTML 字符串
 */
export function renderGameIcon(itemOrKey, options = {}) {
  const size = options.size || 'w-7 h-7';
  const extraClass = options.className || '';
  const fallback = options.fallback || '';

  if (!itemOrKey) {
    return `<div class="${size} ${extraClass} flex items-center justify-center text-sm">${fallback}</div>`;
  }

  // 1. 如果传入的是已包含 SVG 代码的字符串
  if (typeof itemOrKey === 'string' && itemOrKey.includes('<svg')) {
    return `<div class="${size} ${extraClass} inline-flex items-center justify-center pointer-events-none">${itemOrKey}</div>`;
  }

  // 2. 提取查找 Key
  let key = '';
  let slot = '';
  let setId = '';

  if (typeof itemOrKey === 'string') {
    key = itemOrKey;
  } else if (typeof itemOrKey === 'object') {
    key = itemOrKey.id || itemOrKey.key || '';
    slot = itemOrKey.slot || '';
    setId = itemOrKey.setId || '';

    // 如果对象自带 icon 且为图片路径或 SVG
    if (itemOrKey.icon) {
      if (typeof itemOrKey.icon === 'string' && (itemOrKey.icon.startsWith('images/') || itemOrKey.icon.endsWith('.svg') || itemOrKey.icon.endsWith('.png'))) {
        return `<img src="${itemOrKey.icon}" class="${size} ${extraClass} object-contain pointer-events-none select-none drop-shadow" alt="" onerror="this.style.display='none'"/>`;
      }
      if (typeof itemOrKey.icon === 'string' && itemOrKey.icon.includes('<svg')) {
        return `<div class="${size} ${extraClass} inline-flex items-center justify-center pointer-events-none">${itemOrKey.icon}</div>`;
      }
    }
  }

  // 直接命中已知 Registry
  let assetPath = ICON_REGISTRY[key];

  // 按套装匹配
  if (!assetPath && setId && ICON_REGISTRY[setId]) {
    assetPath = ICON_REGISTRY[setId];
  }

  // 按部位匹配
  if (!assetPath && slot && ICON_REGISTRY[slot]) {
    assetPath = ICON_REGISTRY[slot];
  }

  // 智能模糊匹配
  if (!assetPath) {
    const k = String(key).toLowerCase();
    if (k.includes('egg')) assetPath = ICON_REGISTRY['pet_egg'];
    else if (k.includes('pill') || k.includes('dan')) assetPath = ICON_REGISTRY['pill_reborn'];
    else if (k.includes('book')) assetPath = ICON_REGISTRY['skill_book'];
    else if (k.includes('meat') || k.includes('food')) assetPath = ICON_REGISTRY['pet_food'];
    else if (k.includes('crystal') && k.includes('star')) assetPath = ICON_REGISTRY['star_crystal'];
    else if (k.includes('crystal') && k.includes('protect')) assetPath = ICON_REGISTRY['protect_crystal'];
    else if (k.includes('crystal') && k.includes('socket')) assetPath = ICON_REGISTRY['crystal_socket'];
    else if (k.includes('diamond')) assetPath = ICON_REGISTRY['crystal_socket'];
    else if (k.includes('relic')) assetPath = ICON_REGISTRY['relic_holy'];
    else if (k.includes('rune')) assetPath = ICON_REGISTRY['rune_stone'];
    else if (k.includes('key')) assetPath = ICON_REGISTRY['key_bronze'];
    else if (k.includes('sword') || k.includes('blade')) assetPath = ICON_REGISTRY['wpn_sword'];
    else if (k.includes('staff') || k.includes('wand')) assetPath = ICON_REGISTRY['wpn_staff'];
    else if (k.includes('bow')) assetPath = ICON_REGISTRY['wpn_bow'];
    else if (k.includes('robe') || k.includes('cloth')) assetPath = ICON_REGISTRY['arm_robe'];
    else if (k.includes('armor') || k.includes('plate')) assetPath = ICON_REGISTRY['arm_chest'];
    else if (k.includes('helm')) assetPath = ICON_REGISTRY['eq_helmet'];
    else if (k.includes('glove')) assetPath = ICON_REGISTRY['eq_gloves'];
    else if (k.includes('boot')) assetPath = ICON_REGISTRY['eq_boots'];
    else if (k.includes('belt')) assetPath = ICON_REGISTRY['eq_belt'];
    else if (k.includes('pants')) assetPath = ICON_REGISTRY['eq_pants'];
    else if (k.includes('necklace') || k.includes('amulet')) assetPath = ICON_REGISTRY['eq_necklace'];
    else if (k.includes('ring')) assetPath = ICON_REGISTRY['eq_ring'];
    else if (k.includes('potion') && k.includes('hp')) assetPath = ICON_REGISTRY['potion_hp'];
    else if (k.includes('potion') && k.includes('mp')) assetPath = ICON_REGISTRY['potion_mp'];
    else if (k.includes('fish')) assetPath = ICON_REGISTRY['fish_arowana'];
    else if (k.includes('dragon')) assetPath = ICON_REGISTRY['golden_dragon'];
  }

  if (assetPath) {
    return `<img src="${assetPath}" class="${size} ${extraClass} object-contain pointer-events-none select-none drop-shadow filter" alt="" onerror="this.style.display='none'"/>`;
  }

  // 最终后备 (若传入是文本或空)
  return `<span class="${size} ${extraClass} inline-flex items-center justify-center filter drop-shadow select-none">${itemOrKey.icon || fallback || ''}</span>`;
}

